import asyncio
import json
import os
import sys
from pathlib import Path

import numpy as np
from sentence_transformers import SentenceTransformer

from shared.rabbitmq import RabbitMQClient
from shared.utils import model_to_queue

MIDDLEWARE_QUEUE = os.getenv("MIDDLEWARE_QUEUE", "router.requests")
MODELS_JSON_PATH = Path(os.getenv("MODELS_JSON_PATH", "router/models.json"))
EMBEDDING_MODEL_NAME = os.getenv("EMBEDDING_MODEL_NAME", "sentence-transformers/all-MiniLM-L6-v2")

mq_client = RabbitMQClient(
    host=os.getenv("RABBITMQ_HOST", "localhost"),
    user=os.getenv("RABBITMQ_USER", "guest"),
    password=os.getenv("RABBITMQ_PASS", "guest"),
)

# Populated once at startup by load_router_catalog(), then read-only for
# the life of the process -> safe to share across concurrent handlers.
_EMBEDDER: SentenceTransformer | None = None
_MODEL_NAMES: list[str] = []
_MODEL_EMBEDDINGS: np.ndarray | None = None  # shape (n_models, dim), L2-normalized


def _normalize(vectors: np.ndarray) -> np.ndarray:
    """L2-normalize row vectors so a plain dot product == cosine similarity."""
    norms = np.linalg.norm(vectors, axis=-1, keepdims=True)
    norms[norms == 0] = 1e-12
    return vectors / norms


def load_router_catalog() -> None:
    """
    Load router/models.json (generated by scripts/build_manifests.py),
    embed every model description once, and cache the normalized
    embedding matrix in RAM. After this runs, routing a request is just
    one embed + one matrix dot product — no disk or network I/O.
    """
    global _EMBEDDER, _MODEL_NAMES, _MODEL_EMBEDDINGS

    if not MODELS_JSON_PATH.exists():
        raise FileNotFoundError(
            f"{MODELS_JSON_PATH} not found. Run `python scripts/build_manifests.py` first."
        )

    with open(MODELS_JSON_PATH, "r") as f:
        catalog = json.load(f)

    if not catalog:
        raise ValueError(f"{MODELS_JSON_PATH} is empty — router has no models to choose from.")

    print(f"[*] Loading embedding model '{EMBEDDING_MODEL_NAME}' (CPU)...")
    _EMBEDDER = SentenceTransformer(EMBEDDING_MODEL_NAME, device="cpu")

    _MODEL_NAMES = [entry["name"] for entry in catalog]
    descriptions = [entry["description"] for entry in catalog]

    raw_embeddings = _EMBEDDER.encode(descriptions, convert_to_numpy=True, show_progress_bar=False)
    _MODEL_EMBEDDINGS = _normalize(raw_embeddings).astype(np.float32)

    print(f"[OK] Cached embeddings for {len(_MODEL_NAMES)} model(s): {_MODEL_NAMES}")


def select_model(prompt: str) -> str:
    """
    Embed the incoming prompt and pick the model whose description sits
    closest to it in embedding space (cosine similarity via dot product
    on pre-normalized vectors — O(n_models) per request).
    """
    if _EMBEDDER is None or _MODEL_EMBEDDINGS is None:
        raise RuntimeError("Router catalog not loaded. Call load_router_catalog() first.")

    prompt_embedding = _EMBEDDER.encode([prompt], convert_to_numpy=True, show_progress_bar=False)
    prompt_embedding = _normalize(prompt_embedding).astype(np.float32)[0]

    similarities = _MODEL_EMBEDDINGS @ prompt_embedding  # (n_models,)
    best_idx = int(np.argmax(similarities))

    print(f"[*] Semantic match: '{_MODEL_NAMES[best_idx]}' (score={similarities[best_idx]:.4f})")
    return _MODEL_NAMES[best_idx]


async def route_message(message) -> None:
    """Receive a request from the Gateway, semantically pick a model, forward it."""
    try:
        payload = json.loads(message.body.decode())
        prompt = payload.get("prompt", "")

        if not prompt:
            raise ValueError("Payload is missing the required 'prompt' field.")

        selected_model = select_model(prompt)
        worker_queue = model_to_queue(selected_model)

        payload["model"] = selected_model

        print(f"[*] Routing request {message.correlation_id} -> model={selected_model} -> {worker_queue}")

        # forward() preserves correlation_id + reply_to, so the Worker
        # can reply directly to the Gateway's private callback queue.
        await mq_client.forward(message=message, routing_key=worker_queue, payload=payload)

    except json.JSONDecodeError:
        print("[!] Received invalid JSON")
        raise
    except Exception as e:
        print(f"[!] Error routing message: {e}")
        raise


async def main():
    sys.stdout.reconfigure(line_buffering=True)

    load_router_catalog()

    await mq_client.connect(service_name="Semantic Router")
    print(f"[*] Router listening on {MIDDLEWARE_QUEUE}")

    await mq_client.channel.set_qos(prefetch_count=1)
    queue = await mq_client.channel.declare_queue(MIDDLEWARE_QUEUE, durable=True)

    async def wrapper(message):
        async with message.process():
            await route_message(message)

    await queue.consume(wrapper)
    print(f"[*] Waiting for requests on {MIDDLEWARE_QUEUE}")

    try:
        await asyncio.Future()
    finally:
        await mq_client.close()


if __name__ == "__main__":
    asyncio.run(main())